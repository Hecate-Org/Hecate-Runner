"""SIEM Telemetry Forwarder for closed-loop adversary emulation testing.

Ships process execution, file, and network telemetry events generated by BAS agents
(e.g., Caldera sandbox container) directly into Splunk Enterprise/Cloud for live detection
rule validation.
"""

from __future__ import annotations

import json
import logging
import os
from typing import Any

import httpx

log = logging.getLogger(__name__)


def forward_events_to_splunk(
    events: list[dict[str, Any]],
    index: str = "main",
    sourcetype: str = "hecate:telemetry",
    host: str | None = None,
    token: str | None = None,
    username: str | None = None,
    password: str | None = None,
    verify_ssl: bool | None = None,
    timeout_sec: float = 15.0,
) -> int:
    """Ingest a list of telemetry events into Splunk via Simple Receiver REST API.

    Args:
        events: List of telemetry event dictionaries.
        index: Target Splunk index (default: "main").
        sourcetype: Splunk sourcetype (default: "hecate:telemetry").
        host: Splunk management URL (default: read from SPLUNK_HOST).
        token: Splunk auth token (default: read from SPLUNK_TOKEN).
        username: Splunk username (default: read from SPLUNK_USERNAME).
        password: Splunk password (default: read from SPLUNK_PASSWORD).
        verify_ssl: Whether to verify SSL certificates (default: SPLUNK_VERIFY_SSL).
        timeout_sec: Request timeout in seconds.

    Returns:
        Number of events successfully accepted by Splunk.
    """
    if not events:
        return 0

    try:
        from pathlib import Path
        from dotenv import load_dotenv

        load_dotenv(override=False)
        for env_path in (
            Path.cwd() / ".env",
            Path("/home/chemch/betas/Hecate-Public/.env"),
            Path.home() / "betas" / "Hecate-Public" / ".env",
        ):
            if env_path.exists():
                load_dotenv(env_path, override=False)
    except Exception:
        pass

    splunk_host = (host or os.getenv("SPLUNK_HOST") or "https://localhost:8089").rstrip("/")
    if not splunk_host.startswith(("http://", "https://")):
        splunk_host = f"https://{splunk_host}"

    splunk_token = token or os.getenv("SPLUNK_TOKEN")
    splunk_user = username or os.getenv("SPLUNK_USERNAME") or "admin"
    splunk_pass = password or os.getenv("SPLUNK_PASSWORD")

    if verify_ssl is None:
        verify_ssl = os.getenv("SPLUNK_VERIFY_SSL", "false").lower() in ("true", "1", "yes")

    endpoint = f"{splunk_host}/services/receivers/simple"
    params = {"index": index, "sourcetype": sourcetype}

    # Format events as newline-delimited JSON
    payload_lines = [json.dumps(ev) for ev in events]
    data = "\n".join(payload_lines)

    headers = {"Content-Type": "application/json"}
    auth = None
    if splunk_token:
        auth_val = (
            splunk_token
            if splunk_token.startswith(("Bearer ", "Basic ", "Splunk "))
            else f"Bearer {splunk_token}"
        )
        headers["Authorization"] = auth_val
    elif splunk_pass:
        auth = (splunk_user, splunk_pass)

    try:
        with httpx.Client(verify=verify_ssl, timeout=timeout_sec) as client:
            resp = client.post(endpoint, params=params, headers=headers, auth=auth, content=data)
            # If Bearer token was rejected with 401, retry with basic auth if password available
            if resp.status_code == 401 and splunk_pass and headers.get("Authorization"):
                headers.pop("Authorization", None)
                resp = client.post(
                    endpoint,
                    params=params,
                    headers=headers,
                    auth=(splunk_user, splunk_pass),
                    content=data,
                )
            resp.raise_for_status()
            log.info("Successfully forwarded %d event(s) to Splunk index '%s'", len(events), index)
            return len(events)
    except Exception as exc:
        log.warning("Failed to forward telemetry events to Splunk: %s", exc)
        return 0
